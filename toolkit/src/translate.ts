declare const Scratch: ScratchHost;
export function tr<Key extends string | undefined = undefined>(key?: Key, parameters?: TranslationValues): TranslationResult<Key> {
    const store = (globalThis as typeof globalThis & {ReduxStore?: EditorStore}).ReduxStore;
    const locale = store?.getState().locales || {};
    const code = locale.locale || Scratch.translate.language || document.documentElement.lang || navigator.language;
    const language = String(code || '').toLowerCase().split(/[-_]/)[0];
    const lang: Language = Object.hasOwn(strings, language) ? language as Language : 'en';
    if(key === undefined) return {
        lang,
        isRtl: !!locale.isRtl
    } as TranslationResult<Key>;

    const fallback = strings.en as Record<string, string>;
    const dictionary = strings[lang] as Record<string, string>;
    const native = key === 'delete' ? locale.messages?.['paint.paintEditor.delete'] : undefined;
    const text = native || dictionary[key] || fallback[key] || key;
    const result = parameters ? text.replace(/\{(\w+)\}/g, (placeholder: string, name: string) => Object.hasOwn(parameters, name) ? String(parameters[name]) : placeholder) : text;
    return result as TranslationResult<Key>;
}

type Language = keyof typeof strings;
type TranslationValues = Record<string, string | number>;
interface Locale {
    lang: Language;
    isRtl: boolean;
}
type TranslationResult<Key> = Key extends undefined ? Locale : string;
interface EditorStore {
    getState(): {
        locales?: {
            locale?: string;
            isRtl?: boolean;
            messages?: Record<string, string>
        }
    };
}